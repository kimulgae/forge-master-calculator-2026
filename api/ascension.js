export default function handler(req, res) {
    if (req.method !== 'POST') return res.status(405).json({ message: 'POST 요청만 받습니다.' });
    if (req.body.type === 'wakeup') return res.status(200).json({ success: true, message: '서버 기상 완료!' });

    const { type, currentMode, cur, tar, curr, prog, cost, ext, spd, dis, isCombine } = req.body;
    let ascCur = req.body.ascCur !== undefined ? req.body.ascCur : 0;
    let ascTar = req.body.ascTar !== undefined ? req.body.ascTar : 0;

    let resHTML = "";
    let rarityHTML = "";
    let isTarget = (currentMode === 'target');

    // ----------------------------------------
    // 스킬 / 알(펫) / 탈것 공통 검증 및 계산
    // ----------------------------------------
    if (type === 'skill' || type === 'pet' || type === 'mount') {
        const maxCurLvl = (ascCur >= 3) ? 150 : 100;
        const maxTarLvl = (ascTar >= 3) ? 150 : 100;
        if (ascCur < 0 || ascCur > 3 || cur < 1 || cur > maxCurLvl) {
            return res.status(200).json({ success: false, message: `<span style="color:#ed4245; font-weight:bold;">현재 승천/레벨을 올바르게 입력하세요 (0~2승천: 1~100, 3승천: 1~150).</span>` });
        }

        const getPulls = type === 'skill' ? getSkillPulls : (type === 'pet' ? getPetPulls : getMountPulls);
        const rarityArr = type === 'skill' ? skillRarity : (type === 'pet' ? petRarity : mountRarity);
        let absCur = (ascCur * 100) + cur;

        if (isTarget) {
            if (ascTar < 0 || ascTar > 3 || tar < 1 || tar > maxTarLvl) {
                return res.status(200).json({ success: false, message: `<span style="color:#ed4245; font-weight:bold;">목표 승천/레벨을 올바르게 입력하세요 (0~2승천: 1~100, 3승천: 1~150).</span>` });
            }
            let absTar = (ascTar * 100) + tar;
            if (absTar > 450 || absCur >= absTar) {
                return res.status(200).json({ success: false, message: `<span style="color:#ed4245; font-weight:bold;">목표 수치(승천 및 레벨)가 현재보다 커야 합니다.</span>` });
            }

            let total = 0;
            for (let i = absCur; i < absTar; i++) {
                let { asc, lvl } = fromAbsSummon(i);
                if (asc < 3 && lvl === 100) continue; // 승천 전환 시 소환 횟수 0
                total += getPulls(lvl);
            }
            total = Math.max(0, total - prog);

            if (type === 'skill') {
                let finalCost = Math.ceil(total / 5) * cost;
                resHTML = `[목표 ${ascTar}승천 ${tar}레벨] 필요 소환: <strong>${total.toLocaleString()}회</strong><br>예상 소모 비용: <strong>${formatNum(finalCost)}</strong> (5회 ${cost} 기준)`;
            } else if (type === 'pet') {
                let exp = Math.ceil(total / (1 + ext / 100));
                resHTML = `[목표 ${ascTar}승천 ${tar}레벨] 순수 필요 소환: <strong>${total.toLocaleString()}회</strong><br>추탈 적용 실제 소환: <strong>${exp.toLocaleString()}회</strong><br>예상 비용 (100 고정): <strong>${formatNum(exp * 100)}</strong>`;
            } else {
                let exp = Math.ceil(total / (1 + ext / 100));
                let finalCost = exp * cost;
                if (isCombine) {
                    total *= 2; exp *= 2; finalCost *= 2;
                    resHTML = `<span style="color:#2ecc71; font-size:0.85rem;">[길드전 합치기 ×2 적용됨]</span><br>`;
                }
                resHTML += `[목표 ${ascTar}승천 ${tar}레벨] 순수 필요 소환: <strong>${total.toLocaleString()}회</strong><br>추탈 적용 실제 소환: <strong>${exp.toLocaleString()}회</strong><br>예상 소모 비용: <strong>${formatNum(finalCost)}</strong>`;
            }
            rarityHTML = generateRarityHTML(tar, rarityArr, RarityNames, RarityColors);
        } else {
            let unitCost = (type === 'pet') ? 100 : cost;
            let pullsPerPurchase = (type === 'skill') ? 5 : (1 + ext / 100);
            let pullsAvail = Math.floor(curr / unitCost) * pullsPerPurchase;
            let totalAvail = pullsAvail + prog;

            if (type === 'mount' && isCombine) {
                totalAvail /= 2;
                resHTML = `<span style="color:#2ecc71; font-size:0.85rem;">[길드전 합치기 ×2 적용됨]</span><br>`;
            }

            let absLevel = absCur;
            let usedPulls = 0;

            while (absLevel < 450) {
                let { asc, lvl } = fromAbsSummon(absLevel);
                let needNext = (asc < 3 && lvl === 100) ? 0 : getPulls(lvl);
                if (totalAvail >= needNext) {
                    totalAvail -= needNext;
                    usedPulls += needNext;
                    absLevel++;
                } else { break; }
            }

            if (type === 'mount' && isCombine) {
                totalAvail *= 2;
                usedPulls *= 2;
            }

            let { asc: finalAsc, lvl: finalLvl } = fromAbsSummon(absLevel);

            if (absLevel >= 450) {
                let boughtPulls = Math.max(0, usedPulls - prog);
                let purchases = Math.ceil(boughtPulls / pullsPerPurchase);
                let costSpent = purchases * unitCost;
                let actualPullsGained = purchases * pullsPerPurchase;
                let finalProgress = (prog + actualPullsGained) - usedPulls;
                let remCurr = curr - costSpent;
                resHTML += `[보유 재화 소진 시] 도달 가능 최대 레벨: <strong style="color:#2ecc71;">3승천 150레벨 (만렙)</strong><br>만렙 후 남은 재화: <strong>${formatNum(remCurr)}</strong><br>남은 횟수(진행도): <strong>${Math.floor(finalProgress)}</strong>`;
            } else {
                let needNext = (finalAsc < 3 && finalLvl === 100) ? 0 : getPulls(finalLvl);
                resHTML += `[보유 재화 소진 시] 도달 가능 최대 레벨: <strong>${finalAsc}승천 ${finalLvl}레벨</strong><br>남은 횟수(진행도): <strong>${Math.floor(totalAvail)} / ${needNext}</strong>`;
            }
            rarityHTML = generateRarityHTML(finalLvl, rarityArr, RarityNames, RarityColors);
        }
    }
    // ----------------------------------------
    // 대장간 계산 (0~2승천: 1~35, 3승천: 1~50)
    // ----------------------------------------
    else if (type === 'forge') {
        let actualDis = 1 - (dis / 100);
        let actualSpd = 1 + (spd / 100);
        const maxCurLvl = (ascCur >= 3) ? 50 : 35;
        const maxTarLvl = (ascTar >= 3) ? 50 : 35;

        if (ascCur < 0 || ascCur > 3 || cur < 1 || cur > maxCurLvl) {
            return res.status(200).json({ success: false, message: `<span style="color:#ed4245; font-weight:bold;">현재 레벨을 올바르게 입력하세요 (0~2승천: 1~35, 3승천: 1~50).</span>` });
        }
        let absCur = (ascCur * 35) + cur;

        if (isTarget) {
            if (ascTar < 0 || ascTar > 3 || tar < 1 || tar > maxTarLvl) {
                return res.status(200).json({ success: false, message: `<span style="color:#ed4245; font-weight:bold;">목표 레벨을 올바르게 입력하세요 (0~2승천: 1~35, 3승천: 1~50).</span>` });
            }
            let absTar = (ascTar * 35) + tar;
            if (absTar > 155) return res.status(200).json({ success: false, message: `<span style="color:#ed4245; font-weight:bold;">최대 성장(3승천 50레벨)을 초과했습니다.</span>` });
            if (absCur >= absTar) return res.status(200).json({ success: false, message: `<span style="color:#ed4245; font-weight:bold;">목표 수치(승천 및 레벨)가 현재보다 커야 합니다.</span>` });

            let c = 0, t = 0, s = 0;
            for (let i = absCur; i < absTar; i++) {
                let { asc, lvl } = fromAbsForge(i);
                if (asc < 3 && lvl === 35) {
                    c += 3000000; t += 0; s += 0;
                } else {
                    let baseData = forgeBase[lvl - 1];
                    c += baseData.c; t += baseData.t; s += baseData.s;
                }
            }

            resHTML = `[목표 ${ascTar}승천 ${tar}레벨] 소모 코인 (비감 적용): <strong>${formatNum(Math.floor(c * actualDis))}</strong><br>건뛰 소모 비용: <strong>${s.toLocaleString()}</strong><br>최종 소요 시간 (시감 적용): <strong>${formatTime(t / actualSpd)}</strong>`;
            rarityHTML = generateRarityHTML(tar, forgeRarity, ForgeNames, ForgeColors);
        } else {
            let absLevel = absCur;
            let timeAccum = 0;
            let costAccum = 0;
            let remainingCurr = curr;

            while (absLevel < 155) {
                let { asc, lvl } = fromAbsForge(absLevel);
                let nextCost = 0, nextTime = 0;

                if (asc < 3 && lvl === 35) {
                    nextCost = Math.floor(3000000 * actualDis);
                    nextTime = 0;
                } else {
                    let baseData = forgeBase[lvl - 1];
                    nextCost = Math.floor(baseData.c * actualDis);
                    nextTime = baseData.t;
                }

                if (remainingCurr >= nextCost) {
                    remainingCurr -= nextCost;
                    costAccum += nextCost;
                    timeAccum += nextTime;
                    absLevel++;
                } else { break; }
            }

            let { asc: finalAsc, lvl: finalLvl } = fromAbsForge(absLevel);

            if (absLevel >= 155) {
                resHTML = `[보유 코인 소진 시] 도달 가능 최대 레벨: <strong style="color:#2ecc71;">3승천 50레벨 (만렙)</strong><br>총 소모 코인: <strong>${formatNum(costAccum)}</strong><br>만렙 후 남은 코인: <strong>${formatNum(remainingCurr)}</strong><br>총 소요 시간: <strong>${formatTime(timeAccum / actualSpd)}</strong>`;
            } else {
                resHTML = `[보유 코인 소진 시] 도달 가능 최대 레벨: <strong>${finalAsc}승천 ${finalLvl}레벨</strong><br>총 소모 코인: <strong>${formatNum(costAccum)}</strong><br>사용 후 남은 코인: <strong>${formatNum(remainingCurr)}</strong><br>총 소요 시간: <strong>${formatTime(timeAccum / actualSpd)}</strong>`;
            }
            rarityHTML = generateRarityHTML(finalLvl, forgeRarity, ForgeNames, ForgeColors);
        }
    }

    res.status(200).json({ success: true, message: resHTML, rarityData: rarityHTML });
}
